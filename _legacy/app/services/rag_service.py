    async def query(
        self, 
        query: str, 
        context: Optional[str] = None,
        max_tokens: int = 1000,
        temperature: float = 0.7
    ) -> Dict[str, Any]:
        """
        Process a RAG query.
        
        Args:
            query: The user's query
            context: Optional context to include
            max_tokens: Maximum tokens for response
            temperature: Temperature for generation
            
        Returns:
            Dictionary containing answer, sources, and confidence
        """
        try:
            # 1. Retrieve relevant documents
            relevant_docs = await self._retrieve_documents(query)
            
            # 2. Build context from retrieved documents
            context_text = self._build_context(relevant_docs, context)
            
            # 3. Generate response using LLM
            answer = await self._generate_response(
                query=query,
                context=context_text,
                max_tokens=max_tokens,
                temperature=temperature
            )
            
            # 4. Calculate confidence based on source relevance
            confidence = self._calculate_confidence(relevant_docs)
            
            # 5. Prepare sources
            sources = self._prepare_sources(relevant_docs)
            
            return {
                'answer': answer,
                'sources': sources,
                'confidence': confidence
            }
            
        except Exception as e:
            logger.error(f"RAG query processing failed: {str(e)}")
            raise
    
